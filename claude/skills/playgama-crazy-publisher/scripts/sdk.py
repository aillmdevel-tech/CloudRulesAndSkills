"""Stage «SDK» of playgama-crazy-publisher: scan, feature matrix by launch status, install templates, static and runtime checks.
Imported by publisher.py (commands sdk-scan, sdk-config, sdk-install, sdk-check, sdk-run)."""
import functools, http.server, json, os, re, shutil, sys, threading, time

TPL = os.path.join(os.path.dirname(__file__), '..', 'templates', 'sdk')
DEFAULT = {'cg_launch': 'basic', 'ads': True, 'rewarded': True, 'banner': True, 'iap': False, 'products': []}
SKIP = {'node_modules', 'dist', 'release', '.git', 'promo', 'tools', 'tests', 'docs', 'references', 'assets_src', 'art', 'publish'}
PAUSE_RE = re.compile(r'\b(game_?over|gameOver|level_?(complete|end|failed|up)|onDeath|on_death|died|respawn|revive|lose|onWin|victory|'
                      r'round_?end|roundEnd|finish(ed)?Run|results?Screen|showResult|nextLevel|restart)\b', re.I)
NAV_RE = re.compile(r'(menu|settings|shop|store|open|close|button|tab|back)', re.I)


def src_files(root, sub='src'):
    base = os.path.join(root, sub)
    for r, ds, fs in os.walk(base):
        ds[:] = [d for d in ds if d not in SKIP and not d.startswith('.')]
        for f in fs:
            if f.endswith(('.ts', '.tsx', '.js', '.jsx', '.vue')) and not f.endswith('.d.ts') and '.test.' not in f:
                yield os.path.join(r, f)


def read(p):
    try: return open(p, encoding='utf-8', errors='replace').read()
    except OSError: return ''


def rel(root, p): return os.path.relpath(p, root)


def features(sdk):
    """Platform rules x game status -> what each build may use. Single source for config.ts and checks."""
    ads, rw, bn, iap = sdk['ads'], sdk['ads'] and sdk['rewarded'], sdk['ads'] and sdk['banner'], sdk['iap']
    full = sdk['cg_launch'] == 'full'
    return {
        'playgama': {'interstitial': ads, 'rewarded': rw, 'banner': bn, 'iap': iap},
        # Basic Launch: CrazyGames monetization is off (ads, banners, IAP). Full: ads via SDK; IAP is invite-only (Xsolla), not templated.
        'crazygames': {'interstitial': ads and full, 'rewarded': rw and full, 'banner': bn and full, 'iap': False},
        'web': {'interstitial': ads, 'rewarded': rw, 'banner': bn, 'iap': iap},
    }


def config_ts(sdk):
    f = features(sdk)
    rows = ',\n'.join(f"  {k}: {{ interstitial: {str(v['interstitial']).lower()}, rewarded: {str(v['rewarded']).lower()}, "
                      f"banner: {str(v['banner']).lower()}, iap: {str(v['iap']).lower()} }}" for k, v in f.items())
    return ('/** Generated by `pub sdk-config` from publish/STATE.json (sdk). Edit there, not here.\n'
            f" *  Status: CrazyGames {sdk['cg_launch']} launch · ads {'on' if sdk['ads'] else 'off'} · rewarded {'on' if sdk['rewarded'] else 'off'}"
            f" · banner {'on' if sdk['banner'] else 'off'} · IAP {'on' if sdk['iap'] else 'off'}. */\n"
            f'export const FEATURES = {{\n{rows},\n}} as const;\n')


def ad_calls(root):
    """placements used in code: ads.interstitial('x') / ads.rewarded('x') / purchases.purchase('x')"""
    out = {'interstitial': {}, 'rewarded': {}, 'purchase': {}}
    for p in src_files(root):
        if '/platform/' in p or '/dev/' in p: continue
        for n, line in enumerate(read(p).splitlines(), 1):
            for kind, rx in (('interstitial', r"ads\.interstitial\(\s*['\"]([\w-]+)"), ('rewarded', r"ads\.rewarded\(\s*['\"]([\w-]+)"),
                             ('purchase', r"purchases\.purchase\(\s*['\"]([\w-]+)")):
                for m in re.finditer(rx, line): out[kind].setdefault(m.group(1), []).append(f'{rel(root, p)}:{n}')
    return out


def sdk_state(s): return {**DEFAULT, **(s.get('sdk') or {})}


# ---------------------------------------------------------------- scan
def cmd_sdk_scan(a, load):
    root = a.project; s = load(a); sdk = sdk_state(s)
    pkg = json.load(open(os.path.join(root, 'package.json'))) if os.path.exists(os.path.join(root, 'package.json')) else {}
    deps = {**pkg.get('dependencies', {}), **pkg.get('devDependencies', {})}; sc = pkg.get('scripts', {})
    has = lambda f: os.path.exists(os.path.join(root, f))
    print('стек:', ', '.join(k for k in ('three', 'pixi.js', 'phaser', 'playcanvas', '@babylonjs/core', 'vite') if k in deps) or 'не определён')
    print('платформенный слой:', {f: has('src/platform/' + f) for f in ('types.ts', 'index.ts', 'config.ts', 'playgama.ts', 'crazygames.ts')},
          '· web:', has('src/dev/webPlatform.ts'))
    print('Playgama Bridge:', 'npm ' + deps['@playgama/bridge'] if '@playgama/bridge' in deps else 'НЕТ',
          '· config:', has('public/playgama-bridge-config.json'), '· vite-плагин:', '@playgama/bridge/vite' in read(os.path.join(root, 'vite.config.ts')))
    print('сборки:', {k: k in sc for k in ('dev:playgama', 'build:playgama', 'build:crazygames', 'pack:playgama', 'pack:crazygames')})
    html = read(os.path.join(root, 'index.html'))
    print('загрузочный экран:', 'есть (#boot)' if 'id="boot"' in html else 'НЕТ', '· boot/progress:', has('src/boot/progress.ts') or has('src/engine/bootProgress.ts'))
    raw = {'storage': [], 'sdk': [], 'audio': []}
    for p in src_files(root):
        if '/platform/' in p or '/dev/' in p: continue
        t = read(p)
        for n, line in enumerate(t.splitlines(), 1):
            if re.search(r'\b(localStorage|sessionStorage|indexedDB)\b', line): raw['storage'].append(f'{rel(root, p)}:{n}')
            if re.search(r'window\.bridge|\bbridge\.(platform|advertisement|storage|payments)|CrazyGames\.SDK', line): raw['sdk'].append(f'{rel(root, p)}:{n}')
    print('хранилище мимо платформы:', raw['storage'][:8] or 'нет', '· SDK мимо платформы:', raw['sdk'][:8] or 'нет')
    calls = ad_calls(root)
    for k, v in calls.items(): print(f'{k}:', {pl: len(w) for pl, w in v.items()} or 'нет')
    pts = []
    for p in src_files(root):
        if '/platform/' in p or '/dev/' in p: continue
        for n, line in enumerate(read(p).splitlines(), 1):
            if PAUSE_RE.search(line) and len(pts) < 25: pts.append(f'{rel(root, p)}:{n}: {line.strip()[:110]}')
    print('кандидаты логических пауз (interstitial):'); [print('  ' + x) for x in pts] or print('  не найдено, ищи вручную')
    print('статус игры (STATE.sdk):', json.dumps(sdk, ensure_ascii=False))
    print('матрица:', json.dumps(features(sdk)))


# ---------------------------------------------------------------- config
def cmd_sdk_config(a, load, save):
    root = a.project; s = load(a); sdk = sdk_state(s)
    for k in ('cg_launch',):
        v = getattr(a, k, None)
        if v: sdk[k] = v
    for k in ('ads', 'rewarded', 'banner', 'iap'):
        v = getattr(a, k, None)
        if v: sdk[k] = v == 'on'
    if a.products is not None:
        sdk['products'] = [dict(zip(('id', 'type'), (x.split(':') + ['consumable'])[:2])) for x in a.products.split(',') if x]
    s['sdk'] = sdk; save(a, s)
    os.makedirs(os.path.join(root, 'src/platform'), exist_ok=True)
    open(os.path.join(root, 'src/platform/config.ts'), 'w', encoding='utf-8').write(config_ts(sdk))
    # playgama-bridge-config.json: keep what is there, set placements from code and payments from STATE
    cp = os.path.join(root, 'public/playgama-bridge-config.json'); os.makedirs(os.path.dirname(cp), exist_ok=True)
    cfg = json.load(open(cp, encoding='utf-8')) if os.path.exists(cp) else {}
    calls = ad_calls(root); adv = cfg.setdefault('advertisement', {})
    adv.setdefault('minimumDelayBetweenInterstitial', 60)
    for kind, fb in (('interstitial', 'pause'), ('rewarded', 'reward'), ('banner', 'menu')):
        blk = adv.setdefault(kind, {}); ids = [p['id'] for p in blk.get('placements', [])]
        for pl in (calls.get(kind) or {}):
            if pl not in ids: ids.append(pl)
        if kind == 'banner' and not ids: ids = ['menu']
        if ids: blk['placements'] = [{'id': i} for i in ids]; blk.setdefault('placementFallback', ids[0])
        blk['disable'] = not features(sdk)['playgama'][kind]
    if sdk['iap'] and sdk['products']: cfg['payments'] = [{'id': p['id']} for p in sdk['products']]
    else: cfg.pop('payments', None)
    json.dump(cfg, open(cp, 'w', encoding='utf-8'), ensure_ascii=False, indent=4)
    wp = os.path.join(root, 'src/dev/webPlatform.ts')
    if os.path.exists(wp):
        t = read(wp); cat = json.dumps([{'id': p['id'], 'price': '$0.99'} for p in sdk['products']] if sdk['iap'] else [])
        t2 = re.sub(r'/\*PRODUCTS\*/.*?/\*END\*/', '/*PRODUCTS*/' + cat + '/*END*/', t, flags=re.S)
        if t2 != t: open(wp, 'w', encoding='utf-8').write(t2)
    print('STATE.sdk:', json.dumps(sdk, ensure_ascii=False))
    for k, v in features(sdk).items(): print(f'  {k:10s}', ' '.join(f"{f}={'✓' if on else '·'}" for f, on in v.items()))
    print('записано: src/platform/config.ts, public/playgama-bridge-config.json')


