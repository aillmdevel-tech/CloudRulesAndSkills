def cmd_sdk_install(a, load, save):
    root = a.project; s = load(a); sdk = sdk_state(s); s['sdk'] = sdk; save(a, s)
    done, kept = [], []
    files = ['src/platform/types.ts', 'src/platform/index.ts', 'src/platform/playgama.ts', 'src/platform/crazygames.ts',
             'src/dev/webPlatform.ts', 'src/boot/progress.ts', 'tools/pack.py']
    pkg_p = os.path.join(root, 'package.json'); pkg = json.load(open(pkg_p)) if os.path.exists(pkg_p) else {}
    if 'three' in {**pkg.get('dependencies', {}), **pkg.get('devDependencies', {})}: files.append('src/boot/threeHook.ts')
    for f in files:
        dst = os.path.join(root, f); os.makedirs(os.path.dirname(dst), exist_ok=True)
        if os.path.exists(dst) and not a.force:
            shutil.copy(os.path.join(TPL, f), dst + '.publisher-new'); kept.append(f)
        else:
            shutil.copy(os.path.join(TPL, f), dst); done.append(f)
    # loading screen into index.html
    ip = os.path.join(root, 'index.html'); html = read(ip)
    if html and 'id="boot"' not in html:
        frag = read(os.path.join(TPL, 'boot.html'))
        bg = a.boot_bg or ''
        tips = json.loads(read(a.tips)) if a.tips else DEFAULT_TIPS
        rep = {'{{COLOR_TOP}}': a.color_top, '{{COLOR_BOTTOM}}': a.color_bottom, '{{FILL_LIGHT}}': '#a8ff5a', '{{FILL_DARK}}': '#4fc41e',
               '{{FONT}}': a.font, '{{BG_LAND}}': f"url('{bg}')" if bg else 'none', '{{BG_PORT}}': f"url('{a.boot_bg_port or bg}')" if bg else 'none',
               '{{ICON}}': f"url('{a.boot_icon}')" if a.boot_icon else 'none', '{{TIPS_JSON}}': json.dumps(tips, ensure_ascii=False)}
        for k, v in rep.items(): frag = frag.replace(k, v)
        if not a.boot_icon: frag = frag.replace('<div class="logo"></div>', '')
        html = re.sub(r'(<body[^>]*>)', lambda m: m.group(1) + '\n' + frag, html, count=1)
        open(ip, 'w', encoding='utf-8').write(html); done.append('index.html (#boot)')
    elif html: kept.append('index.html: #boot уже есть')
    # package.json scripts
    if pkg:
        sc = pkg.setdefault('scripts', {}); add = {
            'dev:playgama': 'vite --host 127.0.0.1 --mode playgama',
            'build:playgama': ('tsc --noEmit && ' if 'typescript' in {**pkg.get('dependencies', {}), **pkg.get('devDependencies', {})} else '') + 'vite build --mode playgama',
            'build:crazygames': ('tsc --noEmit && ' if 'typescript' in {**pkg.get('dependencies', {}), **pkg.get('devDependencies', {})} else '') + 'vite build --mode crazygames',
            'pack:playgama': 'npm run build:playgama && python3 tools/pack.py playgama',
            'pack:crazygames': 'npm run build:crazygames && python3 tools/pack.py crazygames'}
